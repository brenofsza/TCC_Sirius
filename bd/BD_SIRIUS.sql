CREATE TABLE PASTA (
    ID_PASTA INT AUTO_INCREMENT PRIMARY KEY,
    COD_USU INT NOT NULL,
    NOME_PASTA VARCHAR(50) NOT NULL,

    FOREIGN KEY (COD_USU) REFERENCES USUARIO(ID_USU)
);

CREATE TABLE MATERIAL_SALVO (
    ID_SALVO INT AUTO_INCREMENT PRIMARY KEY,
    COD_USU INT NOT NULL,
    COD_MATERIAL INT NOT NULL,
    COD_PASTA INT NOT NULL,
    DATA_SALVO DATE NOT NULL,

    FOREIGN KEY (COD_USU) REFERENCES USUARIO(ID_USU),
    FOREIGN KEY (COD_MATERIAL) REFERENCES MATERIAL(ID_MATERIAL),
    FOREIGN KEY (COD_PASTA) REFERENCES PASTA(ID_PASTA)
);

